  description: string;
  keywords: string[];
  intro: string;
  sections: LandingSection[];
  deliveryDays: string;
  deliveryNote: string;
  ctaTitle: string;
  catalogHref: string;
  /** Для городов — именительный падеж */
  cityName?: string;
  /** Предложный падеж для «в …» */
  cityIn?: string;
  region?: string;
  caseReference?: string;
  /** Для ключевых страниц и сфер применения */
  primaryKeyword?: string;
  /** ID сферы из applications.ts */
