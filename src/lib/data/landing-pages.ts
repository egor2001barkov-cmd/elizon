export type LandingType = "city" | "keyword" | "application" | "cylinder";

export interface LandingSection {
  title: string;
  paragraphs: string[];
}

export interface LandingPage {
  slug: string;
  type: LandingType;
  h1: string;
  title: string;
  description: string;
  keywords: string[];
  intro: string;
  sections: LandingSection[];
  deliveryDays: string;
  deliveryNote: string;
  ctaTitle: string;
  catalogHref: string;
  /** Для городов — именительный падеж */
  cityName?: string;
  /** Предложный падеж для «в …» */
  cityIn?: string;
  region?: string;
  caseReference?: string;
  /** Для ключевых страниц и сфер применения */
  primaryKeyword?: string;
  /** ID сферы из applications.ts */
  applicationId?: string;
  specPdfUrl?: string;
  /** Карточка цены на лендинге */
  priceLabel?: string;
  priceValue?: string;
  priceNote?: string;
  /** Hero-изображение (public path) */
  heroImage?: string;
  heroImageAlt?: string;
  /** ID товаров каталога для карточек и schema Product */
  relatedProductIds?: string[];
  /** FAQ на посадочной (schema FAQPage) */
  faqItems?: { question: string; answer: string }[];
}

